function toService(
  masterId: string,
  [subcategoryId, value, durationMin]: ServiceRow,
  i: number,
): MasterService {
  if (!findSubcategory(subcategoryId)) throw new Error(`Unknown subcategory ${subcategoryId}`);
  return { id: `${masterId}-s${i}`, subcategoryId, price: price(value), durationMin };
}

function toPortfolio(masterId: string, count: number, seed: number): PortfolioPhoto[] {
  return Array.from({ length: count }, (_, i) => ({
    id: `${masterId}-p${i}`,
    url: null,
    hue: (seed * 37 + i * 41) % 360,
  }));
}

function phoneFor(i: number): string {
  const n = String(1_234_567 + i * 73_517).slice(-7);
  const op = ['29', '33', '44', '25'][i % 4];
  return `+375 (${op}) ${n.slice(0, 3)}-${n.slice(3, 5)}-${n.slice(5, 7)}`;
}

